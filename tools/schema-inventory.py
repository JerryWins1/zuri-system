#!/usr/bin/env python3
"""What the Zuri app requires the database to contain.

The schema itself is not in this repo — migrations 1 to 27 and every function
live only inside the live Supabase project, which is the problem this file
exists to soften. It cannot produce a rebuild script: it reads the app's own
code and writes down every table, view and function the app will break without.

So it is a checklist, not a backup. If the database were ever lost, this says
what a rebuilt one must have before the app would run again. Regenerate it
whenever the app gains a table:

    python3 tools/schema-inventory.py > SCHEMA-INVENTORY.md
"""
import collections
import glob
import re
import subprocess
import datetime

FILES = sorted(
    f for f in glob.glob("preview/js/*.js") + glob.glob("preview/*.html") + glob.glob("js/*.js")
    if ".min." not in f
)

tables = collections.defaultdict(set)
rpcs = collections.defaultdict(set)
columns = collections.defaultdict(set)
writes = collections.defaultdict(set)

for path in FILES:
    src = open(path, encoding="utf-8", errors="ignore").read()
    for m in re.finditer(r"\.from\(\s*['\"]([a-z0-9_]+)['\"]", src):
        tables[m.group(1)].add(path)
    for m in re.finditer(r"\.rpc\(\s*['\"]([a-z0-9_]+)['\"]", src):
        rpcs[m.group(1)].add(path)
    for m in re.finditer(
        r"\.from\(\s*['\"]([a-z0-9_]+)['\"]\s*\)\s*\.select\(\s*['\"]([^'\"]{0,400})['\"]", src
    ):
        for col in re.split(r"[,\s]+", m.group(2)):
            col = col.split("(")[0].split(":")[0].strip()
            if re.fullmatch(r"[a-z0-9_]+", col or ""):
                columns[m.group(1)].add(col)
    # a table the app writes to matters more than one it only reads
    for m in re.finditer(
        r"\.from\(\s*['\"]([a-z0-9_]+)['\"]\s*\)\s*\.(insert|update|upsert|delete)\b", src
    ):
        writes[m.group(1)].add(m.group(2))


def rev():
    try:
        return subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"], capture_output=True, text=True, check=True
        ).stdout.strip()
    except Exception:
        return "unknown"


out = []
w = out.append
w("# What the database must contain")
w("")
w("Generated by `tools/schema-inventory.py` from the app's own code at commit "
  f"`{rev()}`, {datetime.date.today().isoformat()}. Do not edit by hand.")
w("")
w("**This is not a backup.** The schema — migrations 1 to 27, the row-security rules "
  "that protect the customer records, and every function below — exists only inside "
  "the live Supabase project. If that project is lost there is nothing here to restore "
  "from. This page only says what a rebuilt database would have to provide before the "
  "app would run again, which is the difference between a long rebuild and an "
  "impossible one.")
w("")
w(f"## Tables and views the app uses — {len(tables)}")
w("")
w("| name | written to | columns the code names |")
w("| --- | --- | --- |")
for t in sorted(tables):
    verbs = ", ".join(sorted(writes[t])) if writes[t] else "read only"
    cols = ", ".join(sorted(columns[t])) if columns[t] else "—"
    w(f"| `{t}` | {verbs} | {cols} |")
w("")
w("A column list is what the code spells out literally; a `select('*')` leaves it blank, "
  "so an empty cell means unknown, never none.")
w("")
w(f"## Functions the app calls — {len(rpcs)}")
w("")
for r in sorted(rpcs):
    w(f"- `{r}()`")
w("")
w("Each is a database function. The app fails at the point of use if one is missing, "
  "not at startup, so a half-rebuilt database looks healthy until somebody presses the "
  "wrong button.")
print("\n".join(out))
